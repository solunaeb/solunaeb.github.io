// 같은 말이 금방 다시 나오지 않도록, 목록을 섞어서 하나씩 꺼내 쓰고 다 쓰면 다시 섞음
const bags = new Map();
export function say(kind, grow) {
  const st = stageOf(grow);
  const list = L[kind]?.[st] || L.idle[0];
  const key = kind + st;
  let bag = bags.get(key);
  if (!bag || !bag.left.length) {
    const left = list.map((_, i) => i);
    for (let i = left.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [left[i], left[j]] = [left[j], left[i]]; }
    if (bag && left.length > 1 && left[left.length - 1] === bag.last) left.unshift(left.pop());   // 바로 앞의 말과 겹치지 않게
    bag = { left, last: bag?.last };
    bags.set(key, bag);
  }
  const i = bag.left.pop();
  bag.last = i;
  return list[i];
}

