// 한 바퀴를 다 돌기 전에는 같은 말이 다시 나오지 않도록 섞어 둔 순서 (항상 같은 순서)
function shuffled(list, seed) {
  const a = list.map((_, i) => i);
  let x = seed;
  const rnd = () => ((x = (x * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}
const ORDER = shuffled(LOVE_PINGS, 1119);

// seq: 몇 번째 알림인지 (기기마다 1씩 늘어남), hour: 한국 시각의 시(0~23)
export function loveLine(seq, hour) {
  const n = Math.abs(seq);
  if (hour >= 6 && hour < 10 && n % 3 === 0) return LOVE_MORNING[Math.floor(n / 3) % LOVE_MORNING.length];
  if ((hour >= 22 || hour < 2) && n % 3 === 0) return LOVE_NIGHT[Math.floor(n / 3) % LOVE_NIGHT.length];
  return LOVE_PINGS[ORDER[n % ORDER.length]];
}
