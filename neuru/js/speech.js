export function say(kind, grow) {
  const list = L[kind]?.[stageOf(grow)] || L.idle[0];
  return list[Math.floor(Math.random() * list.length)];
}

// 꽃말 — 물 준 횟수에 맞춰 자연스럽게
export function flowerTalk(name, meaning, n, grow) {
  const st = stageOf(grow);
  if (n === 1) return [`${name} 씨앗이야! 꽃말은 '${meaning}'이래.`, `${name}를 심었어. 꽃말이 '${meaning}'래. 예쁘지?`, `${name}의 꽃말은 '${meaning}'이야. 오늘부터 같이 키우자.`][st];
  if (n === 7) return [`${name} 쑥쑥! '${meaning}'도 쑥쑥!`, `${name}가 벌써 이만큼 컸어. '${meaning}'도 이렇게 자라나 봐.`, `일주일째야. '${meaning}'이라는 꽃말처럼, 마음도 매일 물을 줘야 자라.`][st];
  if (n === 14) return [`봉오리 생겼다! '${meaning}' 곧 핀다!`, `봉오리가 맺혔어. '${meaning}'이 피어날 준비를 하나 봐.`, `봉오리는 기다림의 모양이야. '${meaning}'도 곧 활짝 필 거야.`][st];
  if (n >= 21) return [`${name} 피었다! '${meaning}'!`, `${name}가 활짝 폈어! 꽃말은 '${meaning}'. 우리 이야기 같지?`, `21번의 물이 '${meaning}'이 되었어. 기다림은 결국 꽃이 되는구나.`][st];
  return null;
}

